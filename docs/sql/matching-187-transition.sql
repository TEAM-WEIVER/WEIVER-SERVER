-- 필수 선행 단계: 구버전 스케줄러·이벤트 소비를 포함한 쓰기를 중지하고 DB 백업을 확보한다.
-- 새 애플리케이션을 기동하기 전에 배포 실행 담당자가 ON_ERROR_STOP=1로 실행한다.
-- 대상 DB 및 search_path를 확인한다. 테이블/알림 행/match_id 값은 삭제하지 않는다.
BEGIN;

LOCK TABLE match_results, notifications IN ACCESS EXCLUSIVE MODE;

ALTER TABLE notifications ADD COLUMN IF NOT EXISTS jd_id bigint;

UPDATE notifications n
SET jd_id = m.jd_id
FROM match_results m
WHERE n.match_id = m.match_id AND n.jd_id IS NULL;

DO $$
DECLARE
    fk record;
BEGIN
    IF EXISTS (SELECT 1 FROM notifications WHERE jd_id IS NULL) THEN
        RAISE EXCEPTION 'notifications.jd_id backfill is incomplete';
    END IF;

    FOR fk IN
        SELECT conname FROM pg_constraint
        WHERE contype = 'f'
          AND conrelid = 'notifications'::regclass
          AND confrelid = 'match_results'::regclass
          AND (SELECT attnum FROM pg_attribute
               WHERE attrelid = 'notifications'::regclass AND attname = 'match_id') = ANY(conkey)
    LOOP
        EXECUTE format('ALTER TABLE notifications DROP CONSTRAINT %I', fk.conname);
    END LOOP;
END $$;

ALTER TABLE notifications ALTER COLUMN jd_id SET NOT NULL;

CREATE TABLE IF NOT EXISTS matching_processed_events (
    matching_processed_event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id varchar(255) NOT NULL UNIQUE,
    create_time timestamp(6) NOT NULL,
    update_time timestamp(6)
);

COMMIT;
